def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--only", nargs="*", help="build only these slugs (the catalog lists only them)")
    parser.add_argument("--work", type=Path, default=ROOT / ".work", help="where the checkouts go")
    parser.add_argument("--out", type=Path, default=ROOT / "_site", help="the site to write")
    args = parser.parse_args(argv)
    try:
        registry = load_registry()
        entries = [e for e in registry["companions"] if not args.only or e["slug"] in args.only]
        if args.only and len(entries) != len(set(args.only)):
            raise BuildError(f"unknown slug among {args.only}")
        if args.out.exists():
            shutil.rmtree(args.out)
        args.out.mkdir(parents=True)
        args.work.mkdir(parents=True, exist_ok=True)
        rows = []
        for entry in entries:
            print(f"== {entry['slug']}: {entry['repository']} @ {entry['commit'][:12]} / {entry['path']}", flush=True)
            rows.append(build_one(entry, registry, args.work, args.out))
            print(f"   ok: {rows[-1]['records']:,} records -> {rows[-1]['viewer']}", flush=True)
        (args.out / "index.html").write_text(catalog(rows, registry), encoding="utf-8")
        (args.out / "library.json").write_text(
            json.dumps({"schema": "formal-companions/library", "schema_version": 1,
                        "formal_companion": registry["formal_companion"], "companions": rows},
                       indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        (args.out / ".nojekyll").write_text("", encoding="utf-8")
    except BuildError as error:
        print(f"STOP {error}", file=sys.stderr)
        return 1
    print(f"PASS {len(rows)} companion(s) in {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
